#ifndef LLVM_LIB_TARGET_ETCA_ETCASELLOWERING_H
#define LLVM_LIB_TARGET_ETCA_ETCASELLOWERING_H

#include "llvm/CodeGen/SelectionDAG.h"
#include "llvm/CodeGen/TargetLowering.h"

namespace llvm {

namespace ETCAISD {
enum NodeType : unsigned {
  FIRST_NUMBER = ISD::BUILTIN_OP_END,

  /// CMP - Compare operation (sets flags, no dest register)
  CMP,

  /// RET_FLAG - Return from function
  RET_FLAG,

  /// Call - Function call
  CALL,

  /// BR_CC - Branch with condition code + glue
  BR_CC,
};

// Condition codes for ETCA branch instructions.
// These map directly to the 4-bit condition field in the branch encoding.
enum CondCode : unsigned {
  COND_EQ  = 0,  // Equal / Zero (Z)
  COND_NE  = 1,  // Not Equal / Not Zero (~Z)
  COND_LT  = 2,  // Less Than / Negative (N)
  COND_GE  = 3,  // Greater or Equal / Not Negative (~N)
  COND_ULT = 4,  // Unsigned Less Than / Carry (C)
  COND_UGE = 5,  // Unsigned Greater or Equal / No Carry (~C)
  COND_LE  = 10, // Less or Equal (N != V)
  COND_GT  = 11, // Greater (N == V)
  COND_ULE = 12, // Unsigned Less or Equal (C | Z)
  COND_UGT = 13, // Unsigned Greater (~(C | Z))
};
} // namespace ETCAISD

class ETCASubtarget;

class ETCATargetLowering : public TargetLowering {
public:
  explicit ETCATargetLowering(const TargetMachine &TM,
                              const ETCASubtarget &STI);

  // LowerOperation - Provide custom lowering hooks for post-legalization
  // DAG nodes.
  SDValue LowerOperation(SDValue Op, SelectionDAG &DAG) const override;

  // ReplaceNodeResults - Replace the results of a node with results from
  // a different node
  void ReplaceNodeResults(SDNode *N, SmallVectorImpl<SDValue> &Results,
                          SelectionDAG &DAG) const override;

  // getSubtarget - Return the ETCASubtarget object.
  const ETCASubtarget &getSubtarget() const { return STI; }

  // Auto-generated by TableGen
  const char *getTargetNodeName(unsigned Opcode) const override;

  SDValue LowerFormalArguments(SDValue Chain, CallingConv::ID CallConv,
                               bool isVarArg,
                               const SmallVectorImpl<ISD::InputArg> &Ins,
                               const SDLoc &DL, SelectionDAG &DAG,
                               SmallVectorImpl<SDValue> &InVals) const override;

  SDValue LowerReturn(SDValue Chain, CallingConv::ID CallConv,
                      bool isVarArg,
                      const SmallVectorImpl<ISD::OutputArg> &Outs,
                      const SmallVectorImpl<SDValue> &OutVals,
                      const SDLoc &DL,
                      SelectionDAG &DAG) const override;

  SDValue LowerCall(TargetLowering::CallLoweringInfo &CLI,
                    SmallVectorImpl<SDValue> &InVals) const override;

  /// isLegalAddressingMode - Return true if the addressing mode is legal.
  bool isLegalAddressingMode(const DataLayout &DL, const AddrMode &AM, Type *Ty,
                             unsigned AS, Instruction *I = nullptr) const override;

private:
  const ETCASubtarget &STI;

  // Lowering helpers
  SDValue LowerGlobalAddress(SDValue Op, SelectionDAG &DAG) const;
  SDValue LowerConstantPool(SDValue Op, SelectionDAG &DAG) const;
  SDValue LowerJumpTable(SDValue Op, SelectionDAG &DAG) const;
  SDValue LowerBR_CC(SDValue Op, SelectionDAG &DAG) const;
  SDValue LowerBRCOND(SDValue Op, SelectionDAG &DAG) const;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_ETCA_ETCASELLOWERING_H
